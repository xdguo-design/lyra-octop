-- Schema v24: conversation file identities, immutable revisions, segments, and tasks.

CREATE TABLE chat_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
    thread_id TEXT REFERENCES threads(thread_id) ON DELETE CASCADE,
    display_name TEXT NOT NULL,
    current_revision_id TEXT,
    deleted_at BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE(file_id, user_id, agent_id)
);
CREATE INDEX idx_chat_files_thread ON chat_files(user_id, agent_id, thread_id, updated_at DESC);

CREATE TABLE chat_file_revisions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id TEXT NOT NULL UNIQUE,
    file_id TEXT NOT NULL REFERENCES chat_files(file_id) ON DELETE CASCADE,
    parent_revision_id TEXT REFERENCES chat_file_revisions(revision_id),
    workspace_path TEXT NOT NULL UNIQUE,
    sha256 TEXT NOT NULL,
    media_type TEXT NOT NULL,
    byte_size BIGINT NOT NULL CHECK (byte_size >= 0),
    origin_kind TEXT NOT NULL,
    source_refs_json TEXT NOT NULL DEFAULT '[]',
    parse_version INTEGER,
    read_status TEXT NOT NULL DEFAULT 'stored',
    coverage_json TEXT NOT NULL DEFAULT '{}',
    created_at BIGINT NOT NULL,
    UNIQUE(file_id, revision_id)
);
CREATE INDEX idx_chat_file_revisions_file ON chat_file_revisions(file_id, created_at DESC);
CREATE INDEX idx_chat_file_revisions_parent ON chat_file_revisions(parent_revision_id);
ALTER TABLE chat_files ADD CONSTRAINT fk_chat_files_current_revision
    FOREIGN KEY (file_id, current_revision_id)
    REFERENCES chat_file_revisions(file_id, revision_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE chat_file_segments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id TEXT NOT NULL REFERENCES chat_file_revisions(revision_id) ON DELETE CASCADE,
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    locator_json TEXT NOT NULL,
    text TEXT NOT NULL,
    char_count INTEGER NOT NULL CHECK (char_count >= 0),
    UNIQUE(revision_id, ordinal)
);
CREATE INDEX idx_chat_file_segments_revision ON chat_file_segments(revision_id, ordinal);

CREATE TABLE chat_file_tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
    thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
    file_id TEXT REFERENCES chat_files(file_id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    input_revision_id TEXT REFERENCES chat_file_revisions(revision_id),
    output_revision_id TEXT REFERENCES chat_file_revisions(revision_id),
    status TEXT NOT NULL,
    generation INTEGER NOT NULL DEFAULT 1 CHECK (generation > 0),
    lease_until BIGINT,
    idempotency_key TEXT NOT NULL,
    request_hash TEXT NOT NULL,
    request_spec_json TEXT NOT NULL,
    progress_json TEXT NOT NULL DEFAULT '{}',
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    error_code TEXT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE(user_id, thread_id, kind, idempotency_key)
);
CREATE INDEX idx_chat_file_tasks_queue ON chat_file_tasks(status, lease_until, created_at);
CREATE INDEX idx_chat_file_tasks_user ON chat_file_tasks(user_id, status, created_at);

UPDATE _schema_version SET version = 24;
